-- 0030 -- G1.9: core.product.slug, so an anonymous URL stops carrying a UUID.
--
-- ADU-DB-01 v1.12 S9.2 (G1.9)  -  ADU-API-01 v1.7 S12.1, doctrine 5
-- WORK ORDER T6 S2.
--
-- WHY IT IS A DEFECT AND NOT A FEATURE. Doctrine 5: "no internal UUID
-- appears in any public URL ... a UUIDv7 is time-ordered, so a UUID in a
-- public URL leaks signup order and admits walking the space." The
-- storefront's product route is already NAMED {slug} in the contract and has
-- been served by id since C2 (register D-43). The contract was right; the
-- missing column was the defect.
--
-- FOUR TRAPS, each of which fails silently, and what this migration does
-- about them:
--
--  1. FOURTEEN INSERT SITES omit a slug -- one production writer and
--     thirteen tests and load scripts, all raw SQL, none of which would fail
--     to compile. A NOT NULL column would break every one of them, and
--     23502 has NO case in pg-error-translator.ts, so each would surface as
--     an opaque 500 whose log line names the constraint but not the column.
--     => The slug is GENERATED BY A TRIGGER when the insert omits it. Every
--     existing site keeps working, and "generated once at creation" (S9.2)
--     is enforced where creation happens rather than in fourteen places.
--
--  2. A CATCH-AND-RETRY SUFFIX LOOP CANNOT WORK in the request transaction:
--     a 23505 aborts it, and every later statement fails 25P02. There is no
--     SAVEPOINT helper anywhere in apps/api/src.
--     => The suffix is chosen by QUERYING for a free one inside the trigger,
--     before the insert lands. No exception, no retry, no savepoint.
--
--  3. `REVOKE UPDATE (slug) ON core.product FROM adulis_app` WOULD BE A
--     SILENT NO-OP. adulis_app holds TABLE-level UPDATE (relacl
--     adulis_app=arwd), and in PostgreSQL a column-level REVOKE does not
--     subtract from a table-level grant. The column-GRANT idiom used twelve
--     times elsewhere in these migrations does not reach this table.
--     => Immutability is a WRITE-ONCE TRIGGER, copying the shape of
--     core.fn_reservation_price_write_once (0011:222-235) exactly.
--
--  4. A restrict_violation from that trigger WOULD SURFACE AS A 500. The
--     23001 branch of pg-error-translator.ts is a ladder of message matches
--     ending in `return null`, which problem-details.filter.ts turns into
--     INTERNAL. The database would refuse the write correctly and the seller
--     would see a server error.
--     => The message is added to that ladder in the same change.
--
-- IMMUTABLE BECAUSE THE DISTRIBUTION CHANNEL IS A SHARED LINK (S9.2). A
-- seller who renames a product must not break every TikTok post pointing at
-- it. The slug records what the product was called at creation; the name is
-- what it is called now, and they are allowed to differ.

-- 1. The column, nullable for the moment ------------------------------------
ALTER TABLE core.product ADD COLUMN slug text;

-- 2. Slug generation, and the collision rule --------------------------------
--
-- "Generated once at creation from the product name, immutable thereafter,
-- with a numeric suffix on collision within the seller" (S9.2). The scope is
-- the SELLER, not the market: two sellers may both have canvas-tote, and
-- must, because the public path is /{handle}/{slug} and the handle already
-- separates them.
CREATE FUNCTION core.fn_product_slug(p_seller uuid, p_name text)
RETURNS text
LANGUAGE plpgsql STABLE AS $fn$
DECLARE
  v_base text;
  v_try  text;
  v_n    int := 2;
BEGIN
  -- Non-alphanumeric runs collapse to one hyphen; leading and trailing
  -- hyphens go. Amharic and every other non-Latin name reduces to nothing
  -- here, which is why the fallback below is not decoration: a store whose
  -- products are all named in Ge'ez must still get usable URLs.
  v_base := lower(regexp_replace(regexp_replace(p_name, '[^a-zA-Z0-9]+', '-', 'g'),
                                 '(^-+|-+$)', '', 'g'));
  IF v_base IS NULL OR v_base = '' THEN
    v_base := 'product';
  END IF;
  -- Bounded so the suffix always fits and the UNIQUE index stays small.
  v_base := left(v_base, 80);

  v_try := v_base;
  -- Query for a free suffix rather than colliding and retrying: a 23505
  -- inside the caller's transaction aborts it, and nothing in this codebase
  -- can recover from that without a SAVEPOINT that does not exist.
  WHILE EXISTS (SELECT 1 FROM core.product
                 WHERE seller_id = p_seller AND slug = v_try) LOOP
    v_try := v_base || '-' || v_n::text;
    v_n := v_n + 1;
  END LOOP;
  RETURN v_try;
END $fn$;

COMMENT ON FUNCTION core.fn_product_slug(uuid, text) IS
  'G1.9. Slug from a product name, unique within the seller, suffixed -2, -3 on collision. Falls back to "product" when the name reduces to nothing -- a name written entirely in Ge''ez does.';

-- 3. Backfill, before the NOT NULL -----------------------------------------
--
-- Existing rows have no slug and the column is about to be mandatory. The
-- loop is ordered by created_at so the FIRST product to have taken a name
-- keeps the unsuffixed slug, which is the same rule new rows will follow.
DO $backfill$
DECLARE r record;
BEGIN
  FOR r IN SELECT id, seller_id, name FROM core.product
            WHERE slug IS NULL ORDER BY created_at, id
  LOOP
    UPDATE core.product
       SET slug = core.fn_product_slug(r.seller_id, r.name)
     WHERE id = r.id;
  END LOOP;
END $backfill$;

ALTER TABLE core.product ALTER COLUMN slug SET NOT NULL;
ALTER TABLE core.product ADD CONSTRAINT product_slug_unique_per_seller
  UNIQUE (seller_id, slug);

COMMENT ON COLUMN core.product.slug IS
  'G1.9. Generated once at creation, immutable thereafter, unique per seller. The public path is /{handle}/{slug}; doctrine 5 forbids the UUID that used to be there.';

-- 4. Generated on insert, so no writer has to know about it -----------------
CREATE FUNCTION core.fn_product_slug_default() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.slug IS NULL OR NEW.slug = '' THEN
    NEW.slug := core.fn_product_slug(NEW.seller_id, NEW.name);
  END IF;
  RETURN NEW;
END $fn$;

CREATE TRIGGER trg_product_slug_default
  BEFORE INSERT ON core.product
  FOR EACH ROW EXECUTE FUNCTION core.fn_product_slug_default();

-- 5. Immutable, by the idiom this repository already uses -------------------
--
-- core.fn_reservation_price_write_once (0011:222-235) is the same shape and
-- the same ERRCODE. A column-level REVOKE would have looked like the right
-- answer and done nothing, because adulis_app holds table-level UPDATE.
CREATE FUNCTION core.fn_product_slug_write_once() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.slug IS DISTINCT FROM OLD.slug THEN
    RAISE EXCEPTION 'product slug is immutable'
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END $fn$;

CREATE TRIGGER trg_product_slug_write_once
  BEFORE UPDATE ON core.product
  FOR EACH ROW EXECUTE FUNCTION core.fn_product_slug_write_once();

-- The generator is called by the trigger (INVOKER, so it runs as whoever
-- inserts) and may also be called directly by the catalogue service.
REVOKE ALL ON FUNCTION core.fn_product_slug(uuid, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION core.fn_product_slug(uuid, text) TO adulis_app, adulis_migrate;
